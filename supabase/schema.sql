-- CaseWeb Supabase schema
-- Applied once by scripts/migrate-to-supabase.js via SUPABASE_DB_URL.

-- "by default" (not "always") identity columns so the one-off migration
-- script can insert explicit legacy IDs; sequences are re-synced afterward.
create table if not exists personal_cases (
  id                 bigint generated by default as identity primary key,
  firm               text not null,
  round              text,
  industry           text,
  case_type          text,
  problem_statement  text,
  my_approach        text,
  key_insights       text,
  outcome            text,
  date               text,
  notes              text,
  created_at         timestamptz not null default now()
);

create table if not exists cases (
  case_id        bigint generated by default as identity primary key,
  case_title     text not null,
  case_type      text,
  category       text,
  difficulty     text,
  is_numerical   boolean not null default false,
  firm           text,
  page_number    integer,
  case_statement text,
  source_volume  text
);

create table if not exists case_dialogue (
  dialogue_id   bigint generated by default as identity primary key,
  case_id       bigint references cases(case_id) on delete cascade,
  sequence_no   integer,
  speaker       text,
  dialogue_text text
);

create table if not exists case_notes (
  note_id       bigint generated by default as identity primary key,
  case_id       bigint references cases(case_id) on delete cascade,
  note_category text,
  note_text     text,
  sort_order    integer
);

create table if not exists frameworks (
  framework_id   bigint generated by default as identity primary key,
  framework_name text unique
);

create table if not exists case_diagrams (
  diagram_id    bigint generated by default as identity primary key,
  case_id       bigint references cases(case_id) on delete cascade,
  framework_id  bigint references frameworks(framework_id),
  image_path    text,
  diagram_order integer
);

-- Profiles extend auth.users with app-specific fields (name/role).
create table if not exists profiles (
  id         uuid primary key references auth.users(id) on delete cascade,
  email      text not null,
  name       text,
  role       text not null default 'student',
  created_at timestamptz not null default now()
);

create table if not exists case_progress (
  id             bigint generated by default as identity primary key,
  user_id        uuid references profiles(id) on delete cascade,
  case_id        bigint references cases(case_id) on delete cascade,
  status         text,
  reaction       text,
  personal_notes text default '',
  unique (user_id, case_id)
);

-- Only the server (service-role key) talks to these tables, so RLS is
-- enabled with no policies: locks out the anon/public key entirely.
alter table personal_cases enable row level security;
alter table cases          enable row level security;
alter table case_dialogue  enable row level security;
alter table case_notes     enable row level security;
alter table frameworks     enable row level security;
alter table case_diagrams  enable row level security;
alter table profiles       enable row level security;
alter table case_progress  enable row level security;
